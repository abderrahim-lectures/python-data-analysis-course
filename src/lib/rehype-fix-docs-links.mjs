// The content bodies pre-date the Astro/hub rewrite and still link to the old
// Docusaurus `/docs/...` URL scheme, e.g. `/docs/projects/ai-agent` or
// `/docs/data-analysis/normal/week-10`. Those paths no longer exist in the
// static build and would 404 for every reader.
//
// This rewrites them, at render time, to the current locale-aware hub routes
// (see routeSegments.ts): project slugs resolve to their localized slug (via
// projectSlugs.data.json, generated from the localized titles) with the
// English slug as fallback, and the learn-strip `track` word is localised
// (normal/hard -> عادي/صعب/dificil/...).
//
// Deriving locale from the source file path instead of editing ~130 markdown
// files keeps the raw content intact for GitHub/editors while every rendered
// page gets working links.
import fs from 'node:fs';
import {visit} from 'unist-util-visit';

// Inlined from routeSegments.ts — kept as a plain dataset here so this
// render-time plugin doesn't import TypeScript from a .mjs worker context.
const LOCALES = ['ar', 'es', 'fr'];
const NAV_WORDS = {
  en: {learn: 'learn', projects: 'projects', progress: 'progress'},
  ar: {learn: 'تعلم', projects: 'مشاريع', progress: 'تقدم'},
  es: {learn: 'aprender', projects: 'proyectos', progress: 'progreso'},
  fr: {learn: 'apprendre', projects: 'projets', progress: 'progression'},
};
const TRACK_WORDS = {
  en: {normal: 'normal', hard: 'hard'},
  ar: {normal: 'عادي', hard: 'صعب'},
  es: {normal: 'normal', hard: 'dificil'},
  fr: {normal: 'normal', hard: 'difficile'},
};

// English slug -> localized slug per locale (generated by
// scripts/generate-project-slugs.cjs). Read defensively: if the file is
// missing the build must still succeed with English-slug fallback.
let PROJECT_SLUGS = null;
function projectSlugData() {
  if (PROJECT_SLUGS === null) {
    try {
      PROJECT_SLUGS = JSON.parse(
        fs.readFileSync(new URL('./projectSlugs.data.json', import.meta.url), 'utf8'),
      );
    } catch {
      PROJECT_SLUGS = {};
    }
  }
  return PROJECT_SLUGS;
}

const LEARN_SECTIONS = new Set(['python-101', 'data-analysis']);

function localeOf(srcPath) {
  // src/content/learn/<locale?>/<section>/...  (EN has no locale segment)
  // src/content/projects/<locale?>/<slug>.md   (EN has no locale segment)
  const rel = srcPath.replace(/^.*src\/content\/learn\//, 'learn/');
  const m = rel.match(/^learn\/([^/]+)/);
  if (m && LOCALES.includes(m[1])) return m[1];
  const mp = srcPath.match(/src\/content\/projects\/([^/]+)\//);
  if (mp && LOCALES.includes(mp[1])) return mp[1];
  return 'en';
}

export default function rehypeFixDocsLinks() {
  return (tree, file) => {
    const locale = localeOf(String(file.path || file.history?.[0] || ''));
    const nav = NAV_WORDS[locale];
    visit(tree, 'element', (node) => {
      if (node.tagName !== 'a' || typeof node.properties?.href !== 'string') return;
      const href = node.properties.href;
      const m = href.match(/^\/docs\/([^#?]*)/);
      if (!m) return;
      const pathNoAnchor = m[1]; // no leading slash, e.g. projects/ai-agent
      const anchor = href.slice(m[0].length);
      let target;
      if (pathNoAnchor === 'projects' || pathNoAnchor.startsWith('projects/')) {
        const slug = pathNoAnchor.slice('projects'.length); // '' or '/slug'
        let local = slug;
        if (slug && locale !== 'en') {
          local = projectSlugData()[locale]?.[slug] ?? slug;
        }
        target = `/${locale === 'en' ? '' : locale + '/'}${nav.projects}${local}`;
      } else {
        const parts = pathNoAnchor.split('/'); // e.g. ['data-analysis','normal','week-10']
        const section = parts[0];
        if (LEARN_SECTIONS.has(section) && parts.length === 3) {
          const track = TRACK_WORDS[locale][parts[1]];
          const prefix = locale === 'en' ? '' : locale + '/';
          target = `/${prefix}${nav.learn}/${section}/${track}/${parts[2]}`;
        } else {
          // A recognised section/week shape we don't want to guess at; keep the
          // original so the author can fix the copy by hand rather than 404.
          return;
        }
      }
      node.properties.href = target + anchor;
    });
  };
}
